/**
 * Bundle the worker into a downloadable archive, at build time.
 *
 * The source is public, but this deployment's URL is not — so "git clone it and set the URL" would
 * mean either publishing the URL or making someone read it off one screen and type it into another.
 * Instead the site hands out a tarball containing just what a worker needs — the Python package, the
 * scoring config, the taxonomy, and a launcher with **this deployment's URL already baked in** — so
 * there is nothing to configure after unpacking and the URL never leaves the PIN.
 *
 * Staged into a directory and tarred whole rather than using `--transform`, which GNU tar has and
 * macOS's bsdtar does not — this has to produce the same archive on a laptop and on Vercel.
 */
import { execFileSync } from "node:child_process";
import { chmodSync, cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const repo = resolve(web, "..");
const stage = join(web, ".bundle");
const root = join(stage, "grid-worker");
const target = join(web, "public", "grid-worker.tar.gz");

/**
 * Where this bundle will phone home.
 *
 * Vercel sets VERCEL_PROJECT_PRODUCTION_URL on its builders. Locally there is none, so the
 * launcher asks — a dev bundle that silently pointed at production would be worse.
 */
const siteUrl = process.env.VERCEL_PROJECT_PRODUCTION_URL
  ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}`
  : "";

if (!existsSync(join(repo, "carvana_scraper"))) {
  console.warn("[bundle-worker] carvana_scraper/ not found — skipping bundle.");
  process.exit(0);
}

rmSync(stage, { recursive: true, force: true });
mkdirSync(root, { recursive: true });

cpSync(join(repo, "carvana_scraper"), join(root, "carvana_scraper"), {
  recursive: true,
  // Never ship caches or a token: __pycache__ is noise, and .worker-token is a machine identity
  // that must be generated per machine, not handed out with the download.
  filter: (path) => !/__pycache__|\.pyc$|\.worker-token/.test(path),
});
cpSync(join(repo, "config"), join(root, "config"), { recursive: true });
cpSync(join(repo, "requirements.txt"), join(root, "requirements.txt"));

const launcher = `#!/bin/bash
# GRID worker — double-click to run searches on this machine.
#
# Generated by the site, so the URL below is already correct. Safe to re-run.
set -u
cd "$(dirname "$0")" || exit 1

SITE="${siteUrl}"

say()  { printf '\\n\\033[1m%s\\033[0m\\n' "$*"; }
die()  { printf '\\n\\033[31m%s\\033[0m\\n\\n' "$*"; read -r -p "Press Enter to close."; exit 1; }

say "GRID worker"

command -v python3 >/dev/null 2>&1 || die "Python 3 is not installed. Get it from python.org, then run this again."
python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' \\
  || die "Python 3.11 or newer is required."

# Playwright drives real Chrome, not a bundled browser. An aged real-Chrome profile is most of why
# report fetches are not challenged immediately.
[ -d "/Applications/Google Chrome.app" ] \\
  || die "Google Chrome is not installed. Get it from google.com/chrome, then run this again."

if [ -z "$SITE" ]; then
  printf '  Site URL: '
  read -r SITE
  [ -n "$SITE" ] || die "A site URL is required."
fi

say "Installing (first run only)"
python3 -m pip install --quiet --user -r requirements.txt || die "Install failed."

# Two things persist from the login and both matter: profile trust, and the delivery location that
# decides which zip Carvana prices against. Skipped once a profile exists.
if [ ! -d ".browser-profile" ]; then
  say "Opening Chrome once"
  cat <<'EOF'
  Set your delivery ZIP using Carvana's own location picker, then close the window.
  (Typing a zip elsewhere does nothing — Carvana only honours its own picker.)

EOF
  python3 -m carvana_scraper --login || true
fi

say "Running"
echo "  Leave this window open. Ctrl-C to stop."
echo ""
export CARVANA_WEB_URL="$SITE"
exec python3 -m carvana_scraper.worker
`;

// Also as a .env, so `python3 -m carvana_scraper.worker` works directly — the docs tell people to
// run that day to day, and it would otherwise fail with the URL living only inside the launcher.
if (siteUrl) writeFileSync(join(root, ".env"), `CARVANA_WEB_URL=${siteUrl}\n`, "utf8");

const launcherPath = join(root, "start.command");
writeFileSync(launcherPath, launcher, "utf8");
chmodSync(launcherPath, 0o755);

writeFileSync(
  join(root, "README.txt"),
  [
    "GRID worker",
    "",
    "Double-click start.command.",
    "",
    "It installs what it needs, opens Chrome once so you can set your delivery ZIP,",
    "and then runs. Leave the window open — while it is running, searches you submit",
    "on the site run on this machine.",
    "",
    "On first run it prints a link. Open that link once in your browser and your",
    "searches will always run here rather than on whoever else is online.",
    "",
    siteUrl ? `Site: ${siteUrl}` : "",
  ].join("\n"),
  "utf8",
);

mkdirSync(join(web, "public"), { recursive: true });
execFileSync("tar", ["-czf", target, "-C", stage, "grid-worker"], { stdio: "inherit" });
rmSync(stage, { recursive: true, force: true });

console.log(`[bundle-worker] ${target}${siteUrl ? ` (site ${siteUrl})` : " (site prompted at run)"}`);
